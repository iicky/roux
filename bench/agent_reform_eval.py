#!/usr/bin/env python3
"""Agent-reformulation eval (roux-hcwl): does an LLM caller close the vocabulary
gap that a single literal query can't?

roux serves LLM agents, but the hard_queries S-bucket (bench/hard_queries_marlin.json)
tests FROZEN human phrasing — which agents don't use. A real agent reformulates a
plain question into the code's jargon before searching. This harness measures that:
the VARIANTS below were generated by a BLIND subagent given only the 8 S-bucket
human questions + "you are in Marlin C++ firmware" — no gold, no index access — then
fired at the clean baseline index via `roux query --also` (RRF-fused, one call each).

RESULT (2026-06-25, clean Marlin index, no embeddings / doc-bridge / index change):
  one-shot human phrasing  S = 0/8   MRR 0.000   (bench/hard_eval.py)
  agent-reformulated (RRF) S = Hit@5 6/8, Hit@10 8/8, MRR 0.643
Conclusion: lexical+graph is sufficient for the agent audience on known domains;
the caller closes the word-gap for free. See bench/hard_queries_marlin.md.

Usage: python3 bench/agent_reform_eval.py        # uses the clean /tmp Marlin index
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROUX = Path(__file__).resolve().parent.parent / "target" / "release" / "roux"
MARLIN = "/tmp/roux-sources/Marlin"  # built by bench/build_persona_indexes.sh

# Blind-agent reformulations, VERBATIM (no gold/index seen at generation time).
VARIANTS = {
    "1": ["input shaping ringing compensation", "ZV_SHAPING", "linear advance", "INPUT_SHAPING_X", "ftMotion fixed-time motion", "M593"],
    "2": ["thermal runaway protection", "THERMAL_PROTECTION_HOTENDS", "thermal_runaway_protection", "max temp error kill", "MAXTEMP MINTEMP error", "watch period heater"],
    "3": ["linear advance pressure", "LIN_ADVANCE", "M900 K factor", "pressure advance extruder", "advance_ed_ratio", "lin_advance"],
    "4": ["home all axes", "G28 homing", "homeaxis home_all", "auto_home set_axis_is_at_home", "quick_home", "G28 gcode"],
    "5": ["filament runout sensor", "FILAMENT_RUNOUT_SENSOR", "M412 runout", "FilamentSensorBase runout detect", "filament_present out_of_filament", "endstop filament"],
    "6": ["save settings EEPROM", "M500 store eeprom", "configuration_store settings.save", "EEPROM_WRITE persistent", "M501 M502 load defaults", "settings.load"],
    "7": ["junction deviation jerk limit", "CLASSIC_JERK", "max_jerk acceleration", "M205 jerk", "JUNCTION_DEVIATION_MM", "planner jerk"],
    "8": ["babystepping live Z adjust", "BABYSTEPPING", "M290 babystep", "babystep.add_steps Z offset", "babystep_Z live adjust", "M851 probe z offset"],
}
# Strict gold = the original S-bucket gold (bench/hard_queries_marlin.json).
GOLD = {
    "1": ["M593"], "2": ["tr_state_machine"], "3": ["M900"], "4": ["homeaxis", "G28"],
    "5": ["FilamentMonitor", "has_run_out"], "6": ["M500"], "7": ["M205"], "8": ["Babystep"],
}


def run_multi(queries: list[str], top: int = 10) -> list[str]:
    cmd = [str(ROUX), "query", queries[0]]
    for v in queries[1:]:
        cmd += ["--also", v]
    cmd += ["--local", "--format", "json", "--top", str(top)]
    proc = subprocess.run(cmd, cwd=MARLIN, capture_output=True, text=True, timeout=120)
    try:
        data = json.loads(proc.stdout)
    except json.JSONDecodeError:
        return []
    return [s.get("qualified_name") or s.get("name", "") for s in data.get("symbols", [])]


def first_hit(names: list[str], gold: list[str]) -> int | None:
    for i, n in enumerate(names):
        if any(g.lower() in n.lower() for g in gold):
            return i + 1
    return None


def main() -> None:
    h5 = h10 = 0
    mrr = 0.0
    n = len(VARIANTS)
    for k in sorted(VARIANTS):
        rank = first_hit(run_multi(VARIANTS[k]), GOLD[k])
        tag = f"#{rank}" if rank else "MISS"
        if rank:
            h5 += rank <= 5
            h10 += rank <= 10
            mrr += 1.0 / rank
        print(f"  S{k}  {tag:5}  -> {','.join(GOLD[k])}")
    print(f"\nagent-reformulated (search_multi RRF)  S  n={n}  "
          f"Hit@5 {h5}/{n}  Hit@10 {h10}/{n}  MRR {mrr / n:.3f}")
    print("baseline one-shot human phrasing: 0/8, MRR 0.000")


if __name__ == "__main__":
    main()
